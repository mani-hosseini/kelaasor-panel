function enrollment(
  id: number,
  userId: number,
  bootcampId: number,
  status: Enrollment["status"],
  next: number,
  days: number,
  paymentId: number | null,
  notes: string | null = null,
): Enrollment {
  const meta = enrollmentStatusMeta[status];
  return {
    id,
    userId,
    bootcampId,
    status,
    statusLabel: meta.label,
    nextStepBy: next,
    nextStepByDisplay: next === NEXT_STEP_BY.ADMIN ? "ادمین" : "کاربر",
    enrolledAt: daysAgo(days),
    notes,
    paymentId,
  };
}

